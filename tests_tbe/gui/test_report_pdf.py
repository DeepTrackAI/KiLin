"""Check one-page report PDFs and the project folders reports use."""

from __future__ import annotations

from pathlib import Path
from tempfile import TemporaryDirectory
import unittest

from pypdf import PdfReader

from qachat.gui.engine import ChatEngine
from qachat.gui.report_pdf import markdown_to_html, write_report_pdf


def _report(words: int) -> str:
    body = " ".join(["word"] * words)
    return f"# A headline\n\n*Source: p.pdf.*\n\n## The Reason\n{body}\n"


class TestReportPdf(unittest.TestCase):
    """Reports fit one A4 page by shrinking the font, within limits."""

    def setUp(self) -> None:
        folder = TemporaryDirectory()
        self.addCleanup(folder.cleanup)
        self.root = Path(folder.name)

    def test_briefing_length_fits_one_page(self) -> None:
        path = self.root / "brief.pdf"
        pages = write_report_pdf(_report(750), path, label="Briefing")
        self.assertEqual(pages, 1)
        reader = PdfReader(path)
        self.assertEqual(len(reader.pages), 1)
        text = " ".join(reader.pages[0].extract_text().split())
        self.assertIn("A headline", text)
        self.assertIn("BRIEFING", text.upper())

    def test_too_long_reports_more_pages(self) -> None:
        pages = write_report_pdf(_report(3000), self.root / "long.pdf")
        self.assertGreater(pages, 1)

    def test_markdown_is_escaped_and_styled(self) -> None:
        html = markdown_to_html(
            "# T <b>\n## Section\nSome **bold** and *it*.\n- one\n- two"
        )
        self.assertIn("T &lt;b&gt;", html)
        self.assertIn('<p class="section">Section</p>', html)
        self.assertIn("<b>bold</b>", html)
        self.assertIn("<i>it</i>", html)
        self.assertIn("<ul><li>one</li><li>two</li></ul>", html)


class TestProjectFolders(unittest.TestCase):
    """Opened projects get outputs/ and templates/, upgrading target/."""

    def setUp(self) -> None:
        folder = TemporaryDirectory()
        self.addCleanup(folder.cleanup)
        self.root = Path(folder.name)
        self.engine = ChatEngine(self.root, lambda event: None)

    def test_templates_are_copied_once(self) -> None:
        self.engine._prepare_project_folders(self.root)
        briefing = self.root / "templates" / "research_briefing.md"
        self.assertTrue(briefing.is_file())
        self.assertTrue((self.root / "outputs").is_dir())
        # A deleted template stays deleted; an edited one is kept.
        briefing.unlink()
        mine = self.root / "templates" / "mine.md"
        mine.write_text("# Mine\n\n## Notes\n")
        self.engine._prepare_project_folders(self.root)
        self.assertFalse(briefing.exists())
        self.assertEqual(mine.read_text(), "# Mine\n\n## Notes\n")

    def test_target_becomes_outputs_without_old_guides(self) -> None:
        target = self.root / "target"
        (target / "templates").mkdir(parents=True)
        (target / "paper_summary.md").write_text("Kept")
        guide = target / "templates" / "research_briefing_template.md"
        guide.write_text(
            "<!-- Generated by QAChat from a report template "
            "(research_briefing.json) -->\n"
        )
        guide.with_suffix(".pdf").write_bytes(b"%PDF")
        self.engine._prepare_project_folders(self.root)
        outputs = self.root / "outputs"
        self.assertFalse(target.exists())
        self.assertEqual((outputs / "paper_summary.md").read_text(), "Kept")
        self.assertFalse((outputs / "templates").exists())


if __name__ == "__main__":
    unittest.main()
